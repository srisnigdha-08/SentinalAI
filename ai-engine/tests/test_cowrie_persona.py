"""
C1 (docs/COWRIE_COMPLETE_GUIDE.md): the parser reports the persona Cowrie actually serves, read from the header
switch_profile.py writes into cowrie.cfg, so sessions are not credited to a stale recorded profile. Offline:
deliveries go to a fake _send.
"""
import importlib.util
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BEFORE = datetime(2026, 10, 21, 9, 0, tzinfo=timezone.utc).timestamp()  # config written at 09:00
AFTER = datetime(2026, 10, 21, 11, 0, tzinfo=timezone.utc).timestamp()  # config rewritten at 11:00


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def parser(monkeypatch, tmp_path):
    monkeypatch.setenv("HONEYPOT_API_KEY", "offline-persona-key")
    monkeypatch.delenv("COWRIE_PERSONA", raising=False)
    monkeypatch.delenv("COWRIE_CFG", raising=False)
    module = _load("cowrie_parser_persona", ROOT / "honeypot/parsers/log_parser.py")
    monkeypatch.setattr(module, "STATE_DIR", tmp_path / "state")
    module.sent = []
    monkeypatch.setattr(module, "_send", lambda ep, data, retries=0: module.sent.append((ep, data)) or "ok")
    return module


def write_cfg(path, persona, mtime=BEFORE):
    header = f"# Generated by honeypot/switch_profile.py ({persona}). Edit the template there, not this file.\n"
    path.write_text(header + "[honeypot]\nhostname = x\n", encoding="utf-8")
    os.utime(path, (mtime, mtime))


def session(parser, sid="s1", at="2026-10-21T10:00:00.000001Z"):
    """connect + kex: the kex opens the session on the backend."""
    for event in ({"eventid": "cowrie.session.connect", "session": sid, "src_ip": "192.0.2.7", "timestamp": at},
                  {"eventid": "cowrie.client.kex", "session": sid, "src_ip": "192.0.2.7", "hassh": "ab" * 16,
                   "timestamp": at}):
        parser.process(json.dumps(event))
    opened = [d for ep, d in parser.sent
              if ep == "/honeypot/ingest" and d.get("eventType") == "SESSION_OPENED" and d["sessionId"] == sid]
    assert len(opened) == 1
    return opened[0]


def test_persona_from_the_cfg_header_is_sent_with_the_session(parser, tmp_path):
    cfg = tmp_path / "cowrie.cfg"
    write_cfg(cfg, "ubuntu_22")
    parser.COWRIE_CFG = str(cfg)
    assert session(parser)["servedProfile"] == "ubuntu_22"


def test_cowrie_persona_env_overrides_and_invalid_values_are_not_sent(parser, tmp_path, monkeypatch):
    cfg = tmp_path / "cowrie.cfg"
    write_cfg(cfg, "ubuntu_22")
    parser.COWRIE_CFG = str(cfg)
    monkeypatch.setenv("COWRIE_PERSONA", "debian_11")
    assert session(parser, "s1")["servedProfile"] == "debian_11"
    monkeypatch.setenv("COWRIE_PERSONA", "not_a_persona")
    assert "servedProfile" not in session(parser, "s2")


@pytest.mark.parametrize("content", ["[honeypot]\nhostname = svr04\n", "# Generated by hand (ubuntu_22)\n",
                                     "# Generated by honeypot/switch_profile.py (solaris_9).\n"])
def test_unknown_persona_is_omitted_so_the_backend_falls_back(parser, tmp_path, content):
    cfg = tmp_path / "cowrie.cfg"
    cfg.write_text(content, encoding="utf-8")
    os.utime(cfg, (BEFORE, BEFORE))
    parser.COWRIE_CFG = str(cfg)
    assert "servedProfile" not in session(parser)


def test_missing_cfg_is_omitted(parser, tmp_path):
    parser.COWRIE_CFG = str(tmp_path / "absent.cfg")
    assert "servedProfile" not in session(parser)


def test_cfg_rewritten_after_the_session_started_is_not_trusted(parser, tmp_path):
    """A backlog replayed after a persona switch must not be credited to the new persona."""
    cfg = tmp_path / "cowrie.cfg"
    write_cfg(cfg, "debian_11", mtime=AFTER)
    parser.COWRIE_CFG = str(cfg)
    assert "servedProfile" not in session(parser)  # session at 10:00, config from 11:00


def test_persona_is_taken_at_connect_even_if_switched_before_the_kex(parser, tmp_path):
    cfg = tmp_path / "cowrie.cfg"
    write_cfg(cfg, "centos_7")
    parser.COWRIE_CFG = str(cfg)
    at = "2026-10-21T10:00:00.000001Z"
    parser.process(json.dumps({"eventid": "cowrie.session.connect", "session": "s1", "src_ip": "192.0.2.7",
                               "timestamp": at}))
    write_cfg(cfg, "aws_ec2", mtime=AFTER)  # rotator switched persona between connect and kex
    parser.process(json.dumps({"eventid": "cowrie.client.kex", "session": "s1", "src_ip": "192.0.2.7",
                               "hassh": "ab" * 16, "timestamp": at}))
    opened = [d for ep, d in parser.sent if d.get("eventType") == "SESSION_OPENED"]
    assert opened[0]["servedProfile"] == "centos_7"


def test_persona_survives_a_parser_restart_in_saved_state(parser, tmp_path):
    cfg = tmp_path / "cowrie.cfg"
    write_cfg(cfg, "raspberry_pi")
    parser.COWRIE_CFG = str(cfg)
    parser.process(json.dumps({"eventid": "cowrie.session.connect", "session": "s1", "src_ip": "192.0.2.7",
                               "timestamp": "2026-10-21T10:00:00.000001Z"}))
    parser.save_state(1, 0)
    parser._sessions.clear()
    parser.COWRIE_CFG = None  # the restarted parser no longer sees the config
    parser._sessions.update(parser.load_state()["sessions"])
    parser.process(json.dumps({"eventid": "cowrie.client.kex", "session": "s1", "src_ip": "192.0.2.7",
                               "hassh": "ab" * 16, "timestamp": "2026-10-21T10:00:00.000002Z"}))
    opened = [d for ep, d in parser.sent if d.get("eventType") == "SESSION_OPENED"]
    assert opened[0]["servedProfile"] == "raspberry_pi"


