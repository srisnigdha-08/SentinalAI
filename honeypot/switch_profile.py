CFG_PATH = Path(__file__).parent / "cowrie" / "cowrie.cfg"

def generate_config(profile_key):
    if profile_key not in PROFILES:
        print(f"Error: Unknown profile '{profile_key}'. Available options:")
        for k, v in PROFILES.items():
            print(f"  - {k:<14} ({v['os']} | {v['banner']})")
        sys.exit(1)

    p = PROFILES[profile_key]
    # Per-persona filesystems built by build_honeyfs.py, used only when the operator opts in, so an unbuilt
    # persona can never leave Cowrie without files. COWRIE_PERSONA_FS: directory of <persona>.pickle (current
    # Cowrie, [shell] filesystem); COWRIE_PERSONA_HONEYFS: directory of honeyfs trees (older Cowrie,
    # contents_path). windows_srv has neither (Linux shell only).
    linux = profile_key != "windows_srv"
    fs_dir = os.getenv("COWRIE_PERSONA_FS", "").strip()
    honeyfs_dir = os.getenv("COWRIE_PERSONA_HONEYFS", "").strip()
    contents = f"contents_path        = {honeyfs_dir}/{profile_key}\n" if honeyfs_dir and linux else ""
    filesystem = f"filesystem           = {fs_dir}/{profile_key}.pickle\n" if fs_dir and linux else ""
    # Section placement checked against cowrie.cfg.dist (cowrie c7773f4): listen_endpoints, version and
    # forwarding in [ssh]; the uname strings and filesystem in [shell]. Logins come from etc/userdb.txt.
    cfg_content = f"""# Generated by honeypot/switch_profile.py ({profile_key}). Edit the template there, not this file.
[honeypot]
hostname             = {p['hostname']}
log_path             = var/log/cowrie
interactive_timeout  = 180
auth_class           = UserDB
download_path        = ${{honeypot:state_path}}/downloads
download_limit_size  = 10485760
{contents}
[shell]
kernel_version       = {p['kernel_version']}
kernel_build_string  = {p['kernel_build_string']}
hardware_platform    = {p['hardware_platform']}
operating_system     = GNU/Linux
{filesystem}
[ssh]
version              = {p['banner']}
listen_endpoints     = tcp:2222:interface=0.0.0.0
# No direct-tcpip forwarding: attackers must not use the honeypot as a proxy.
forwarding           = false

[output_jsonlog]
enabled = true
logfile = ${{honeypot:log_path}}/cowrie.json

[output_textlog]
enabled = true
logfile = ${{honeypot:log_path}}/cowrie.log

[output_pcap]
enabled = false
logfile = ${{honeypot:log_path}}/pcap/cowrie.pcap

[logging]
log_level = info

[output_sentinelblocker]
enabled = true
"""
    CFG_PATH.write_text(cfg_content, encoding="utf-8")
    print(f"[*] Updated {CFG_PATH}")
    print(f"[+] Active Profile: {profile_key.upper()}")
    print(f"    - OS:       {p['os']}")
    print(f"    - Hostname: {p['hostname']}")
    print(f"    - Kernel:   {p['kernel_version']}")
    print(f"    - Banner:   {p['banner']}")

