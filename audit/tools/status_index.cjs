#!/usr/bin/env node
// F-09: builds audit/STATUS_INDEX.md from audit/FINDINGS.md and audit/FIXES.md without changing either file.
// FINDINGS.md is append-only: a finding opened in one batch is updated or closed by later entries further down,
// so the first entry for an ID is often stale ("OPEN" when it was fixed later). This index gives, per ID, the
// status from the latest entry that states one, and links every entry.
// Usage: node audit/tools/status_index.cjs            (writes audit/STATUS_INDEX.md)
//        node audit/tools/status_index.cjs --check    (exit 1 if the committed index is out of date)
'use strict'
const fs = require('fs')
const path = require('path')

const AUDIT = path.join(__dirname, '..')
const SRC = path.join(AUDIT, 'FINDINGS.md')
const FIXES = path.join(AUDIT, 'FIXES.md')
const OUT = path.join(AUDIT, 'STATUS_INDEX.md')
const OVERRIDES = path.join(AUDIT, 'status_overrides.json')

const ID_RE = /[A-Z][A-Z0-9]*-[A-Z0-9]*\d[A-Z0-9]*(?:-[A-Z0-9]+)?/g
// Order matters: the first pattern found in an entry's status text wins.
const STATUS_RULES = [
  [/\bWITHDRAWN\b/i, 'WITHDRAWN'],
  [/\bREQUIRES (OWNER|USER) ACTION\b|\bREQUIRES APPROVAL\b|\brisk accepted\b|\bACCEPTED\b/i, 'OWNER ACTION / ACCEPTED'],
  [/\bPARTIAL(LY)?\b|\bPARTLY\b|\bMOSTLY\b/i, 'PARTIALLY FIXED'],
  [/\bNOT VERIFIED\b/i, 'NOT VERIFIED'],
  [/\bOPEN\b|\bDEFERRED\b/i, 'OPEN'],
  [/\bRESOLVED\b|\bFIXED\b|\bCLOSED\b|\bVERIFIED\b|\bKEEP\b|\bNO ACTION\b|\bNOT REPRODUCED\b/i, 'FIXED / CLOSED'],
  [/\bDOCUMENTED\b|\bPREPARED\b|\bPRE-REGISTERED\b|\bADDED\b/i, 'DOCUMENTED / PREPARED'],
]
const NO_STATUS = 'NO STATUS RECORDED'

function classify(text) {
  for (const [re, label] of STATUS_RULES) if (re.test(text)) return label
  return null
}

function collect(lines, fixLines) {
  const byId = new Map()
  const add = (id, line, file, text, priority) => {
    if (!byId.has(id)) byId.set(id, { id, entries: [], priority: null })
    const rec = byId.get(id)
    rec.entries.push({ line, file, text: text.trim() })
    if (priority) rec.priority = priority
  }
  lines.forEach((raw, i) => {
    const line = i + 1
    const header = raw.match(/^ID: ([^|]+)\|(.*)$/)
    if (header) {
      const ids = header[1].match(ID_RE) || []
      const fields = header[2].split('|').map((s) => s.trim())
      const priority = (fields.find((f) => /^(Priority: )?P\d\b/.test(f)) || '').match(/P\d/)?.[0] || null
      const statusText = fields.filter((f) => !/^Priority: P\d$|^P\d$/.test(f)).join(' | ')
      for (const id of ids) add(id, line, 'FINDINGS.md', statusText, priority)
      return
    }
    // Status tables in FINDINGS.md: "| SEC-001 | **OPEN, escalated to P0** | evidence |"
    const row = raw.match(/^\|\s*([A-Z][A-Z0-9-]*\d[^|]*)\|\s*([^|]+)\|/)
    if (row) for (const id of row[1].match(ID_RE) || []) add(id, line, 'FINDINGS.md', row[2])
  })
  // FIXES.md rows carry the fix status in a bold cell: "| CORE-001 manual blocks | **FIXED** | ... |"
  fixLines.forEach((raw, i) => {
    const row = raw.match(/^\|([^|]+)\|\s*\*\*([^*]+)\*\*/)
    if (!row) return
    for (const id of row[1].match(ID_RE) || []) if (byId.has(id)) add(id, i + 1, 'FIXES.md', row[2])
  })
  return byId
}

function render(byId, overrides) {
  const rows = [...byId.values()].sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }))
  const counts = {}
  const link = (e) => `[${e.file === 'FIXES.md' ? 'fix ' : ''}${e.line}](${e.file}#L${e.line})`
  const body = rows.map((r) => {
    // Current status: the latest FINDINGS.md entry that states one; otherwise the latest FIXES.md row; otherwise
    // none is recorded (which is not the same as fixed, or as open).
    const stated = (file) => r.entries.filter((e) => e.file === file && classify(e.text)).pop()
    const basis = stated('FINDINGS.md') || stated('FIXES.md') || r.entries.filter((e) => e.file === 'FINDINGS.md').pop()
    const o = overrides[r.id]
    const status = o?.status || classify(basis.text) || NO_STATUS
    counts[status] = (counts[status] || 0) + 1
    const note = (o?.note || basis.text).replace(/\|/g, '/').replace(/\s+/g, ' ').slice(0, 110)
    return `| ${r.id} | ${r.priority || '—'} | ${status}${o ? ' *' : ''} | ${o ? 'override' : link(basis)}: ${note} | ${r.entries.map(link).join(', ')} |`
  })
  const summary = Object.entries(counts)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([k, v]) => `${k}: ${v}`)
    .join(' · ')
  return [
    '# Findings — current status index',
    '',
    'Generated by `node audit/tools/status_index.cjs`; do not edit by hand. `FINDINGS.md` and `FIXES.md` are the',
    'append-only history and are not changed: an early entry saying OPEN may have been closed by a later one.',
    'The status here comes from the **latest** `FINDINGS.md` entry for the ID (its `ID:` header or a status-table',
    'row) that states one, else from the latest status cell for it in `FIXES.md`. NO STATUS RECORDED means neither',
    'file states one: it is not evidence that the finding is fixed, or that it is still open. "Entries" links every',
    'line that records the ID ("fix N" = FIXES.md). A `*` marks a status set by hand in `status_overrides.json`.',
    '',
    `${rows.length} findings. ${summary}`,
    '',
    '| ID | Priority | Current status | Status taken from (truncated) | Entries |',
    '|---|---|---|---|---|',
    ...body,
    '',
  ].join('\n')
}

if (require.main === module) {
  const read = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8').split(/\r?\n/) : [])
  const overrides = fs.existsSync(OVERRIDES) ? JSON.parse(fs.readFileSync(OVERRIDES, 'utf8')) : {}
  const out = render(collect(read(SRC), read(FIXES)), overrides)
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
    if (current !== out) {
      console.error('audit/STATUS_INDEX.md is out of date: run node audit/tools/status_index.cjs')
      process.exit(1)
    }
    console.log('audit/STATUS_INDEX.md is current')
  } else {
    fs.writeFileSync(OUT, out)
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`)
  }
}
module.exports = { classify, collect, render }
